    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable2.getModel();
    modelo.setRowCount(0);

    String alumnoBuscado = txtNombre.getText().trim();

    if (alumnoBuscado.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "No se ha identificado al usuario actual.",
            "Error de Usuario",
            javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    java.io.File archivo = new java.io.File("alumnos_matriculados.txt");

    if (!archivo.exists()) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Aún no hay registros de matrícula en el sistema.",
            "Información",
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
        return;
    }

    try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
        String linea;
        boolean encontroClases = false;

        while ((linea = br.readLine()) != null) {
            if (linea.trim().isEmpty()) continue;

            String[] datos = linea.split("\\|");

            if (datos.length >= 6) {
                String tutor     = datos[0].trim();
                String materia   = datos[1].trim();
                String alumno    = datos[2].trim();
                String modalidad = datos[3].trim();
                String dia       = datos[4].trim();
                String hora      = datos[5].trim();

                if (alumno.equalsIgnoreCase(alumnoBuscado)) {
                    modelo.addRow(new Object[]{materia, tutor, modalidad, dia, hora});
                    encontroClases = true;
                }
            }
        }

        if (!encontroClases) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "El alumno " + alumnoBuscado + " no tiene clases matriculadas aún.",
                "Sin Matrícula",
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }

    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Error al leer el archivo de matrícula: " + e.getMessage(),
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton3ActionPerformed
private void cargarTutoresTXT(String materiaBuscada) {
   DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    File archivo = new File("matriculas_tutores.txt"); 

    if (!archivo.exists()) {
        JOptionPane.showMessageDialog(this, "No se encontró el archivo de tutores.");
        return;
    }

    try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
        String linea;

        while ((linea = br.readLine()) != null) {
            if (linea.trim().isEmpty()) continue;

            String[] datos = linea.split("\\|");

            if (datos.length >= 4 && !datos[0].trim().equalsIgnoreCase("null")) {
                
                String materia   = datos[0].trim();
                String nombre    = datos[1].trim();
                String modalidad = datos[2].trim();
                String diaHora   = datos[3].trim();
                String hora      = (datos.length > 4) ? datos[4].trim() : "";

                if (materia.equalsIgnoreCase(materiaBuscada.trim())) {
                    model.addRow(new Object[]{nombre, materia, modalidad, diaHora, hora});
                }
            }
        }
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Error al leer el archivo: " + ex.getMessage());
        ex.printStackTrace();
    }
}
private void guardarMatricula(String nombreEstudiante, String cuentaEstudiante, 
                             String nombreTutor, String materia, 
                             String modalidad, String dia, String hora) {

    File archivoMatriculas = new File("alumnos_matriculados.txt");

    try (FileWriter fw = new FileWriter(archivoMatriculas, true);
         PrintWriter pw = new PrintWriter(fw)) {

        // Escribir la línea respetando el orden exacto de los datos:
        pw.println(nombreTutor + "|" + materia + "|" + nombreEstudiante + "|" + cuentaEstudiante + "|" + modalidad + "|" + dia + "|" + hora);

        JOptionPane.showMessageDialog(this, 
            "¡Matrícula realizada con éxito!\nQuedaste registrado con el tutor: " + nombreTutor, 
            "Éxito", 
            JOptionPane.INFORMATION_MESSAGE);

    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Error al guardar la matrícula: " + ex.getMessage());
        ex.printStackTrace();
    }
}

