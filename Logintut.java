    private void guardarNuevoUsuario(String usuario, String password, String rol) {
    File archivo = new File("usuarios.txt");

    // Validar si el nombre de usuario ya existe
    if (archivo.exists()) {
        try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                if (linea.trim().isEmpty()) continue;
                String[] datos = linea.split("\\|");
                if (datos.length > 0 && datos[0].trim().equalsIgnoreCase(usuario)) {
                    JOptionPane.showMessageDialog(this, 
                        "El usuario '" + usuario + "' ya existe. Por favor elija otro nombre.", 
                        "Usuario Registrado", 
                        JOptionPane.WARNING_MESSAGE);
                    return;
                }
            }
        } catch (IOException ex) {
            ex.printStackTrace();
        }
    }

    // Guarda con la estructura: Usuario|Contraseña|Rol
    try (FileWriter fw = new FileWriter(archivo, true);
         PrintWriter pw = new PrintWriter(fw)) {

        pw.println(usuario + "|" + password + "|" + rol);

        JOptionPane.showMessageDialog(this, 
            "¡Cuenta de " + rol + " creada con éxito! Ya puedes ingresar.", 
            "Registro Exitoso", 
            JOptionPane.INFORMATION_MESSAGE);

    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, 
            "Error al registrar cuenta: " + ex.getMessage(), 
            "Error", 
            JOptionPane.ERROR_MESSAGE);
    }
}

private boolean validarCredenciales(String usuario, String password, String rolRequerido) {
    File archivo = new File("usuarios.txt");

    if (!archivo.exists()) return false;

    try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
        String linea;
        while ((linea = br.readLine()) != null) {
            if (linea.trim().isEmpty()) continue;
            String[] datos = linea.split("\\|");

            if (datos.length >= 3) {
                if (datos[0].trim().equalsIgnoreCase(usuario) && 
                    datos[1].trim().equals(password) && 
                    datos[2].trim().equalsIgnoreCase(rolRequerido)) {
                    return true;
                }
            }
        }
    } catch (IOException ex) {
        ex.printStackTrace();
    }
    return false;
}    
