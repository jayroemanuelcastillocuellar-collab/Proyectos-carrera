javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
fileChooser.setDialogTitle("Guardar base de datos de tutores");

javax.swing.filechooser.FileNameExtensionFilter filtro = 
    new javax.swing.filechooser.FileNameExtensionFilter("Archivos de Texto (*.txt)", "txt");
fileChooser.setFileFilter(filtro);

fileChooser.setSelectedFile(new java.io.File("matriculas_tutores.txt"));

int seleccion = fileChooser.showSaveDialog(this);

if (seleccion == javax.swing.JFileChooser.APPROVE_OPTION) {
    java.io.File archivoSeleccionado = fileChooser.getSelectedFile();
    String ruta = archivoSeleccionado.getAbsolutePath();

    if (!ruta.toLowerCase().endsWith(".txt")) {
        archivoSeleccionado = new java.io.File(ruta + ".txt");
    }

    // AQUÍ ESTÁ EL CAMBIO: Se agrega ', true' en el FileWriter
    try (java.io.FileWriter fw = new java.io.FileWriter(archivoSeleccionado, true); 
         java.io.PrintWriter pw = new java.io.PrintWriter(fw)) {

        for (int i = 0; i < modelo.getRowCount(); i++) {
            String materia = String.valueOf(modelo.getValueAt(i, 0));
            String modalidad = String.valueOf(modelo.getValueAt(i, 1));
            String dia = String.valueOf(modelo.getValueAt(i, 2));
            String hora = String.valueOf(modelo.getValueAt(i, 3));

            pw.println(materia + "|" + modalidad + "|" + dia + "|" + hora);
        }

        javax.swing.JOptionPane.showMessageDialog(this, 
            "¡Archivo guardado exitosamente en:\n" + archivoSeleccionado.getAbsolutePath());

    } catch (java.io.IOException e) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Error al guardar el archivo: " + e.getMessage(), 
            "Error de Archivo", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}
