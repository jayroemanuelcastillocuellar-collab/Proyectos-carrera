    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    if (cmbMateria.getSelectedIndex() == 0 || 
        cmbModalidad.getSelectedIndex() == 0 || 
        cmbHora.getSelectedIndex() == 0) {
        return; 
    }

    StringBuilder diasSeleccionados = new StringBuilder();

    if (chkLunes.isSelected()) diasSeleccionados.append("Lunes, ");
    if (chkMartes.isSelected()) diasSeleccionados.append("Martes, ");
    if (chkMiercoles.isSelected()) diasSeleccionados.append("Miércoles, ");
    if (chkJueves.isSelected()) diasSeleccionados.append("Jueves, ");
    if (chkViernes.isSelected()) diasSeleccionados.append("Viernes, ");

    if (diasSeleccionados.length() == 0) {
        return; 
    }

    String diasFinal = diasSeleccionados.substring(0, diasSeleccionados.length() - 2);

    String materia = cmbMateria.getSelectedItem().toString();
    String modalidad = cmbModalidad.getSelectedItem().toString();
    String hora = cmbHora.getSelectedItem().toString();
    String nombre = txtNombre.getText();

    DefaultTableModel modelo = (DefaultTableModel) tblMatricula.getModel();
    modelo.insertRow(0, new Object[]{materia, nombre, modalidad, diasFinal, hora});

    limpiarFormulario();
}

