    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblAlumnos.getModel();
modelo.setRowCount(0); 

String tutorBuscado = txtNombre.getText().trim(); 

if (tutorBuscado.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, 
        "Por favor ingrese o seleccione el nombre del tutor.", 
        "Campo Requerido", 
        javax.swing.JOptionPane.WARNING_MESSAGE);
    return;
}

java.io.File archivo = new java.io.File("alumnos_matriculados.txt");

if (!archivo.exists()) {
    javax.swing.JOptionPane.showMessageDialog(this, 
        "No existe el archivo de matrículas de alumnos aún.", 
        "Sin Registros", 
        javax.swing.JOptionPane.INFORMATION_MESSAGE);
    return;
}

try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo))) {
    String linea;
    boolean encontroAlumnos = false;

    while ((linea = br.readLine()) != null) {
        if (linea.trim().isEmpty()) continue; 

        String[] datos = linea.split("\\|");

        if (datos.length >= 6) {
            String tutor    = datos[0].trim();
            String materia  = datos[1].trim();
            String alumno   = datos[2].trim();
            String cuenta   = datos[3].trim();
            String modalidad= datos[4].trim();
            String horario  = datos[5].trim();

            if (tutor.equalsIgnoreCase(tutorBuscado)) {
                modelo.addRow(new Object[]{alumno, cuenta, materia, modalidad, horario});
                encontroAlumnos = true;
            }
        }
    }

    if (!encontroAlumnos) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "No se encontraron alumnos matriculados con el tutor: " + tutorBuscado, 
            "Sin Alumnos", 
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }

} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(this, 
        "Error al leer el archivo de registros: " + e.getMessage(), 
        "Error", 
        javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton4ActionPerformed

private void cargarMisEstudiantes(String tutorBuscado) {
    DefaultTableModel model = (DefaultTableModel) tblAlumnos.getModel();
    model.setRowCount(0); 

    File archivo = new File("alumnos_matriculados.txt");

    if (!archivo.exists()) {
        JOptionPane.showMessageDialog(this, "Aún no hay ningún alumno matriculado en el sistema.");
        return;
    }

    try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
        String linea;
        boolean encontroAlumnos = false;

        while ((linea = br.readLine()) != null) {
            if (linea.trim().isEmpty()) continue;

            String[] datos = linea.split("\\|");

            if (datos.length >= 7) {
                String tutorEnArchivo = datos[0].trim();

                if (tutorEnArchivo.equalsIgnoreCase(tutorBuscado.trim())) {
                    String materia   = datos[1].trim();
                    String alumno    = datos[2].trim();
                    String cuenta    = datos[3].trim();
                    String modalidad = datos[4].trim();
                    String horario   = datos[5].trim() + " " + datos[6].trim();

                    model.addRow(new Object[]{alumno, cuenta, materia, modalidad, horario});
                    encontroAlumnos = true;
                }
            }
        }

        if (!encontroAlumnos) {
            JOptionPane.showMessageDialog(this, "No hay ningún alumno matriculado actualmente con: " + tutorBuscado);
        }

    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Error al leer el archivo de matrículas: " + ex.getMessage());
        ex.printStackTrace();
    }
}
